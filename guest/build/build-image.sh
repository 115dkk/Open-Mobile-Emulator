# Builds the blob-free Android 15 guest image (BlissOS 18 tree) from the inputs pinned in pins.env.
# Run as the build user on a host prepared by setup-build-host.sh.
#
#   build-image.sh init       repo init at the pinned manifest commit (or the ome.xml snapshot)
#   build-image.sh sync       repo sync
#   build-image.sh snapshot   write guest/build/manifest/ome.xml (every project at its commit)
#   build-image.sh aaropa     fetch the pinned installer-environment assets and check their sums
#   build-image.sh modules    experimental Digitalis bridge-only build (OME_TRANSLATOR=digitalis)
#   build-image.sh digitalis-iso  build and collect an opt-in experimental ISO
#   build-image.sh installclean  clean installed output after restoring baseline sources
#   build-image.sh baseline-check  verify no experimental inputs/output remain
#   build-image.sh build      lunch + make iso_img with the blob flags unset
#   build-image.sh collect    copy the ISO, its sha256, build.prop and logs to $OME_BUILD_ROOT/dist
#   build-image.sh all        init sync snapshot aaropa build collect
#
# Environment: OME_REPO_ROOT (this repository; default: two levels above this script),
# OME_BUILD_ROOT (the Android tree; default $HOME/bliss), OME_JOBS (default 6), OME_KEEP_GOING
# (set to 1 to keep building past failures and list them all at the end).
set -euo pipefail

HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
OME_REPO_ROOT=${OME_REPO_ROOT:-$(cd "$HERE/../.." && pwd)}
OME_BUILD_ROOT=${OME_BUILD_ROOT:-$HOME/bliss}
# GitHub answers HTTP 429 to a 16-way sync; 6 jobs with retries stayed under its limit on 2026-10-01.
OME_JOBS=${OME_JOBS:-6}
# Digitalis remains opt-in; experimental ISO collection is separate from baseline.
OME_TRANSLATOR=${OME_TRANSLATOR:-none}
case "$OME_TRANSLATOR" in
    none|digitalis) ;;
    *) echo "unsupported OME_TRANSLATOR: $OME_TRANSLATOR" >&2; exit 2 ;;
esac
# shellcheck source=pins.env
source "$HERE/pins.env"

SNAPSHOT="$HERE/manifest/ome.xml"
AAROPA_SUMS="$HERE/aaropa.sha256"
LOG_DIR="$OME_BUILD_ROOT/ome-logs"
mkdir -p "$OME_BUILD_ROOT" "$LOG_DIR"

say() { printf '==> %s  (%s)\n' "$*" "$(date +%H:%M:%S)"; }

refuse_blob_flags() {
    for flag in $OME_BLOB_FLAGS; do
        if [ -n "${!flag:-}" ]; then
            echo "refusing to build: $flag is set in the environment (blob-free build, CLAUDE.md R3)" >&2
            exit 2
        fi
        unset "$flag"
    done
}

do_init() {
    say "init in $OME_BUILD_ROOT"
    cd "$OME_BUILD_ROOT"
    local depth=()
    [ "${OME_REPO_DEPTH:-0}" -gt 0 ] && depth=(--depth="$OME_REPO_DEPTH")
    if [ -f "$SNAPSHOT" ]; then
        say "using the commit snapshot $SNAPSHOT"
        repo init -u "$BLISS_MANIFEST_URL" -b "$BLISS_MANIFEST_BRANCH" --git-lfs "${depth[@]}" --no-repo-verify </dev/null
        cp "$SNAPSHOT" .repo/manifests/ome.xml
        repo init -m ome.xml </dev/null
    else
        say "no snapshot yet: pinning the manifest repository to $BLISS_MANIFEST_COMMIT"
        repo init -u "$BLISS_MANIFEST_URL" -b "$BLISS_MANIFEST_BRANCH" --git-lfs "${depth[@]}" --no-repo-verify </dev/null
        git -C .repo/manifests fetch --quiet origin "$BLISS_MANIFEST_COMMIT" || true
        git -C .repo/manifests checkout --quiet "$BLISS_MANIFEST_COMMIT" -- . 2>/dev/null || \
            echo "note: could not check the manifest repository out at $BLISS_MANIFEST_COMMIT; the branch tip will be used and recorded by snapshot"
    fi
    git -C .repo/manifests log -1 --format='manifest repository at %H (%cI) %s'
}

do_sync() {
    say "sync (-j$OME_JOBS)"
    cd "$OME_BUILD_ROOT"
    local log="$LOG_DIR/sync-$(date +%Y%m%d-%H%M%S).log"
    # repo sync has returned 0 after "Unable to fully sync the tree" (HTTP 429), so completeness is
    # checked afterwards instead of trusting the exit code.
    repo sync -c --force-sync --no-tags --no-clone-bundle -j"$OME_JOBS" --retry-fetches=3 --optimized-fetch --prune 2>&1 | tee "$log" || true
    local missing=0 total=0
    while IFS= read -r path; do
        total=$((total + 1))
        [ -e "$path/.git" ] || { missing=$((missing + 1)); echo "missing: $path"; }
    done < <(repo list -p)
    say "projects: $total, missing: $missing, errors in log: $(grep -c '^error:' "$log" || true)"
    if [ "$missing" -ne 0 ] || grep -q 'Unable to fully sync' "$log"; then
        echo "sync incomplete; run the sync stage again" >&2
        return 1
    fi
    say "source tree: $(du -sh --exclude=out "$OME_BUILD_ROOT" 2>/dev/null | cut -f1)"
}

do_snapshot() {
    say "snapshot -> $SNAPSHOT"
    cd "$OME_BUILD_ROOT"
    mkdir -p "$(dirname "$SNAPSHOT")"
    repo manifest -r -o "$SNAPSHOT"
    # After the XML declaration, so the file stays well-formed for parsers stricter than repo.
    sed -i '1a <!-- Generated by guest/build/build-image.sh snapshot: every project pinned at the commit that was built. -->' "$SNAPSHOT"
    echo "projects: $(grep -c '<project ' "$SNAPSHOT")"
}

do_aaropa() {
    say "installer-environment assets, release $AAROPA_ROOTFS_RELEASE"
    local dir="$OME_BUILD_ROOT/bootable/aaropa"
    [ -d "$dir" ] || { echo "missing $dir (sync first)" >&2; exit 1; }
    local cache="$OME_BUILD_ROOT/ome-cache/aaropa-$AAROPA_ROOTFS_RELEASE"
    mkdir -p "$cache"
    for f in $AAROPA_ROOTFS_FILES; do
        if [ ! -s "$cache/$f" ]; then
            curl -fL --retry 3 -o "$cache/$f" "https://github.com/BlissOS/aaropa_rootfs/releases/download/$AAROPA_ROOTFS_RELEASE/$f"
        fi
    done
    if [ -s "$AAROPA_SUMS" ]; then
        (cd "$cache" && sha256sum -c "$AAROPA_SUMS")
    else
        (cd "$cache" && sha256sum $AAROPA_ROOTFS_FILES) > "$AAROPA_SUMS"
        echo "recorded $AAROPA_SUMS (commit it):"; cat "$AAROPA_SUMS"
    fi
    # What bootable/aaropa/download.sh does, from the pinned files instead of releases/latest.
    cd "$dir"
    rm -rf iso initrd_lib
    mkdir -p iso
    7z x -y "$cache/grub-rescue.iso" -oiso >/dev/null
    cp "$cache/install.sfs" iso/
    cp "$cache/boot_hybrid.img" .
    tar -xzf "$cache/initrd_lib.tar.gz"
    chmod -R 755 initrd_lib/*
    say "aaropa assets in place: $(du -sh iso | cut -f1)"
}

# vendor/bliss/config/common.mk inherits vendor/extra/product.mk first so a builder can set
# properties. The tree's userdebug lunch still yields ro.debuggable=0 and no
# persist.sys.usb.config, so the image boots with adb off and OME cannot reach it even with the
# host key in /adb_keys (docs/evidence/P3/dod-a15-20261003.md, ADR-0012 decision 4). The install
# helper adds the same line to images built before this; it sees this one and leaves it alone.
write_vendor_extra() {
    local mk="$OME_BUILD_ROOT/vendor/extra/product.mk"
    local marker="# Written by Open Mobile Emulator guest/build/build-image.sh"
    if [ -f "$mk" ] && ! grep -qxF "$marker" "$mk"; then
        echo "refusing to overwrite $mk: it was not written by build-image.sh" >&2
        exit 2
    fi
    mkdir -p "$(dirname "$mk")"
    python3 "$HERE/device_profile.py" "$OME_REPO_ROOT/manifests/device-profile.prop"
    cp "$OME_REPO_ROOT/manifests/device-profile.prop" "$OME_BUILD_ROOT/vendor/extra/ome-device-profile.prop"
    cat > "$mk" <<EOF
$marker
PRODUCT_SYSTEM_PROPERTIES += persist.sys.usb.config=adb
PRODUCT_COPY_FILES += vendor/extra/ome-device-profile.prop:system/etc/ome-device-profile.prop
ifeq (\$(OME_TRANSLATOR),digitalis)
\$(call inherit-product, frameworks/libs/binary_translation/enable_arm64_to_x86_64.mk)
endif
EOF
}

# guest/build/patches/<project path>/*.patch are applied to the synced tree in name order.
# A patch that already applies in reverse is left alone, so a rebuild does not apply it twice;
# one that applies neither way stops the build. The init profile loader owns the published
# identity. The earlier patches prevent unrelated Bliss hooks from overriding that identity
# or changing runtime capabilities and security settings as a side effect.
apply_ome_patches() {
    local patch_root=${1:-$HERE/patches}
    local patch project
    while IFS= read -r patch; do
        project=$(dirname "${patch#"$patch_root/"}")
        if git -C "$OME_BUILD_ROOT/$project" apply --reverse --check "$patch" 2>/dev/null; then
            say "patch already applied: $project/$(basename "$patch")"
        elif git -C "$OME_BUILD_ROOT/$project" apply --check "$patch"; then
            git -C "$OME_BUILD_ROOT/$project" apply "$patch"
            say "patch applied: $project/$(basename "$patch")"
        else
            echo "patch does not apply: $patch" >&2
            exit 2
        fi
    done < <(find "$patch_root" -name '*.patch' -print | {
        if [ "$patch_root" = "$HERE/patches" ]; then
            grep -v -F "$HERE/patches/digitalis/"
        else
            cat
        fi
    } | sort)
}

# The kernel rule (device/generic/common/build/tasks/kernel.mk) runs copy-firmware.sh into
# system/vendor/firmware, and that script stops at links a previous build left there ("File
# exists", then "Broken symlinks found"; 2026-10-03). Before a rebuild the firmware tree and the
# kernel image go together, so the rule runs again from an empty directory instead of an image
# going out with the firmware missing.
reset_kernel_firmware() {
    local product="$OME_BUILD_ROOT/out/target/product/x86_64"
    # installclean removes installed firmware but keeps the kernel object cache.
    # Invalidate bzImage even when that installed directory is already absent.
    if [ -d "$product/system/vendor/firmware" ] || [ -f "$product/obj/kernel/arch/x86_64/boot/bzImage" ]; then
        rm -rf "$product/system/vendor/firmware" "$product/obj/kernel/arch/x86_64/boot/bzImage"
        say "removed the previous firmware tree and bzImage so the kernel rule copies firmware afresh"
    fi
}

# A local manifest affects every build in the shared tree. Never silently build a
# default image from the experimental checkout, nor collect it as the normal ISO.
refuse_experimental_image() {
    if [ "$OME_TRANSLATOR" != none ] || [ -f "$OME_BUILD_ROOT/.repo/local_manifests/ome-digitalis.xml" ] ||
        [ -f "$OME_BUILD_ROOT/out/target/product/x86_64/system/lib64/libberberis_arm64.so" ]; then
        echo "baseline image operations require restored sources and installclean; use digitalis-iso for the opt-in experiment" >&2
        exit 2
    fi
}

do_modules() {
    refuse_blob_flags
    [ "$OME_TRANSLATOR" = digitalis ] || { echo "modules requires OME_TRANSLATOR=digitalis" >&2; exit 2; }
    local project="$OME_BUILD_ROOT/frameworks/libs/binary_translation"
    local revision=f5f1c90b17d0c1df9e9be41534c653a3e74bfc64
    [ "$(git -C "$project" rev-parse HEAD)" = "$revision" ] || {
        echo "install manifest/ome-digitalis.xml and sync the pinned translator first" >&2; exit 2;
    }
    apply_ome_patches "$HERE/patches/digitalis"
    cd "$OME_BUILD_ROOT"
    write_vendor_extra
    export OME_TRANSLATOR BLISS_BUILD_VARIANT LC_ALL=C.UTF-8
    # Module builds need no ISO installer environment. The opt-in vendor-hook
    # patch prevents envsetup from downloading releases/latest behind our back.
    export OME_SKIP_INSTALLER_DOWNLOAD=1
    local log="$LOG_DIR/digitalis-modules-$(date +%Y%m%d-%H%M%S).log"
    (
        set +u +e
        source build/envsetup.sh
        lunch "$BLISS_LUNCH" || exit 2
        if [ "${OME_DIGITALIS_MODULES:-bridge}" = all ]; then
            local modules
            modules=$(get_build_var BERBERIS_PRODUCT_PACKAGES_ARM64_TO_X86_64) || exit 2
            [ -n "$modules" ] || { echo "empty Digitalis product package list" >&2; exit 2; }
            echo "Digitalis product modules: $modules"
            m -j"$OME_JOBS" $modules
        else
            m -j"$OME_JOBS" libberberis_arm64
        fi
        exit $?
    ) 2>&1 | tee "$log"
}

do_digitalis_iso() {
    refuse_blob_flags
    [ "$OME_TRANSLATOR" = digitalis ] || { echo "digitalis-iso requires OME_TRANSLATOR=digitalis" >&2; exit 2; }
    [ "$(git -C "$OME_BUILD_ROOT/frameworks/libs/binary_translation" rev-parse HEAD)" = f5f1c90b17d0c1df9e9be41534c653a3e74bfc64 ] || exit 2
    cd "$OME_BUILD_ROOT"
    local suffix=${OME_DIGITALIS_RUN:-}
    [[ "$suffix" =~ ^[a-zA-Z0-9-]*$ ]] || { echo "invalid OME_DIGITALIS_RUN" >&2; exit 2; }
    [ -z "$suffix" ] || suffix="-$suffix"
    local name="OME-api35-$(date +%Y%m%d)${suffix}-digitalis"
    local dist="$OME_BUILD_ROOT/dist/$(date +%Y%m%d)-$(git -C .repo/manifests rev-parse --short HEAD)${suffix}-digitalis"
    [ ! -e "$dist" ] || { echo "refusing to overwrite experimental dist: $dist" >&2; exit 2; }
    apply_ome_patches
    apply_ome_patches "$HERE/patches/digitalis"
    write_vendor_extra
    # The pinned installer inputs already exist; verify rather than run latest-download hooks.
    (cd ome-cache/aaropa-"$AAROPA_ROOTFS_RELEASE" && sha256sum -c "$AAROPA_SUMS")
    reset_kernel_firmware
    export OME_TRANSLATOR BLISS_BUILD_VARIANT LC_ALL=C.UTF-8 OME_SKIP_INSTALLER_DOWNLOAD=1
    export PATH="$HOME/.cargo/bin:$PATH"
    local log="$LOG_DIR/digitalis-iso-$(date +%Y%m%d-%H%M%S).log"
    (
        set +u +e
        source build/envsetup.sh
        lunch "$BLISS_LUNCH" || exit 2
        local upstream_name
        upstream_name=$(get_build_var BLISS_BUILD_ZIP) || exit 2
        printf '%s\n' "$upstream_name" > "$LOG_DIR/digitalis-upstream-iso-name.txt"
        make -j"$OME_JOBS" iso_img
        exit $?
    ) 2>&1 | tee "$log"
    # Soong's make wrapper does not forward a BLISS_BUILD_ZIP command-line override.
    # Rename the successful build output explicitly before collecting it.
    local upstream_name
    upstream_name=$(cat "$LOG_DIR/digitalis-upstream-iso-name.txt")
    local iso="$OME_BUILD_ROOT/out/target/product/x86_64/$name.iso"
    [ ! -e "$iso" ] || { echo "refusing to overwrite $iso" >&2; exit 2; }
    mv "$OME_BUILD_ROOT/out/target/product/x86_64/$upstream_name.iso" "$iso"
    mkdir -p "$dist"
    cp "$iso" "$dist/"
    (cd "$dist" && sha256sum "$name.iso" > "$name.iso.sha256")
    repo manifest -r -o "$dist/ome.xml"
    cp out/target/product/x86_64/system/build.prop "$dist/build.prop"
    cp "$HERE/pins.env" "$log" "$dist/"
    cp -R "$HERE/patches" "$dist/patches"
    printf '%s\n' "$dist" > "$LOG_DIR/digitalis-last-dist.txt"
    say "experimental ISO: $dist"
}

do_installclean() {
    [ "$OME_TRANSLATOR" = none ] || { echo "restore baseline before installclean" >&2; exit 2; }
    [ ! -f "$OME_BUILD_ROOT/.repo/local_manifests/ome-digitalis.xml" ] || exit 2
    [ "$(git -C "$OME_BUILD_ROOT/frameworks/libs/binary_translation" rev-parse HEAD)" = cf1446707cc8e12aa42c024026d42c95228dea38 ] || exit 2
    cd "$OME_BUILD_ROOT"
    # Use the source-defined Soong clean target without envsetup's vendor download hooks.
    # installClean removes product system/root/images and packaging, not dist/ or object caches.
    TARGET_PRODUCT=bliss_x86_64 TARGET_RELEASE=ap4a TARGET_BUILD_VARIANT=userdebug \
        build/soong/soong_ui.bash --make-mode installclean 2>&1 | tee "$LOG_DIR/digitalis-installclean-$(date +%Y%m%d-%H%M%S).log"
    refuse_experimental_image
}

do_build() {
    refuse_experimental_image
    refuse_blob_flags
    say "build $BLISS_LUNCH variant=$BLISS_BUILD_VARIANT -j$OME_JOBS"
    cd "$OME_BUILD_ROOT"
    write_vendor_extra
    apply_ome_patches
    reset_kernel_firmware
    export BLISS_BUILD_VARIANT
    export PATH="$HOME/.cargo/bin:$PATH"
    export LC_ALL=C.UTF-8
    local log="$LOG_DIR/build-$(date +%Y%m%d-%H%M%S).log"
    # envsetup.sh and lunch read unset variables, so the strict modes are relaxed in this subshell
    # only; make's exit status is the subshell's.
    (
        set +u +e
        # shellcheck disable=SC1091
        source build/envsetup.sh
        lunch "$BLISS_LUNCH" || { echo "lunch $BLISS_LUNCH failed" >&2; exit 2; }
        # OME_KEEP_GOING=1 passes -k so one failing target does not hide the others (diagnosis runs).
        make -j"$OME_JOBS" ${OME_KEEP_GOING:+-k} iso_img
        exit $?
    ) 2>&1 | tee "$log"
    say "build log: $log"
}

do_collect() {
    refuse_experimental_image
    say "collect"
    cd "$OME_BUILD_ROOT"
    local product="out/target/product/x86_64"
    local iso
    iso=$(ls -t "$product"/*.iso 2>/dev/null | grep -v -- '-digitalis.iso$' | head -1 || true)
    [ -n "$iso" ] || { echo "no ISO under $product" >&2; exit 1; }
    local dist="$OME_BUILD_ROOT/dist/$(date +%Y%m%d)-$(git -C .repo/manifests rev-parse --short HEAD)"
    mkdir -p "$dist"
    cp "$iso" "$dist/"
    (cd "$dist" && sha256sum "$(basename "$iso")" > "$(basename "$iso").sha256")
    cp "$product/system/build.prop" "$dist/build.prop" 2>/dev/null || true
    [ -f "$SNAPSHOT" ] && cp "$SNAPSHOT" "$dist/ome.xml"
    cp "$HERE/pins.env" "$dist/pins.env"
    cp "$LOG_DIR"/build-*.log "$dist/" 2>/dev/null || true
    say "dist: $dist"; ls -la "$dist"
}

case "${1:-}" in
    init|sync|snapshot|all) refuse_experimental_image ;;
esac

case "${1:-}" in
    init) do_init ;;
    sync) do_sync ;;
    snapshot) do_snapshot ;;
    aaropa) do_aaropa ;;
    modules) do_modules ;;
    digitalis-iso) do_digitalis_iso ;;
    installclean) do_installclean ;;
    baseline-check) refuse_experimental_image ;;
    build) do_build ;;
    collect) do_collect ;;
    all) do_init; do_sync; do_snapshot; do_aaropa; do_build; do_collect ;;
    *) sed -n '2,20p' "$0" | sed 's/^# \{0,1\}//'; exit 1 ;;
esac
