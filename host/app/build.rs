#![forbid(unsafe_code)]

fn main() {
    let manifest = tauri_build::AppManifest::new().commands(&[
        "app_snapshot",
        "host_check_refresh",
        "wizard_continue",
        "wizard_skip",
        "wizard_defer",
        "open_help",
        "app_quit",
        "whpx_enable",
        "artifact_download_start",
        "artifact_download_cancel",
        "guest_image_select",
        "guest_create",
        "guest_select",
        "guest_delete",
        "guest_reinstall",
        "guest_start",
        "guest_stop",
        "guest_restart",
        "guest_root_set",
        "guest_volume_set",
        "stage_rect_changed",
        "stage_hidden",
        "screenshot_save",
        "app_install_pick",
        "app_install_cancel",
        "app_uninstall",
        "app_launch",
        "input_host_key",
        "input_profile_select",
        "input_suspend_toggle",
        "input_overlay_toggle",
        "input_profile_delete",
        "input_profile_save",
        "input_binding_upsert",
        "input_binding_remove",
        "input_editor_toggle",
        "input_auto_apply_set",
        "input_suspend_hotkey_set",
        "display_preset_apply",
        "display_custom_apply",
        "display_refresh_set",
        "display_vsync_set",
        "stage_fit_set",
        "settings_save",
        "update_check",
        "update_install",
        "diagnostics_export",
        "open_logs_folder",
        "open_screenshots_folder",
        "open_home_folder",
        "copy_to_clipboard",
        "open_registration_page",
        "google_account_add_open",
        "guest_window_to_front",
    ]);
    tauri_build::try_build(tauri_build::Attributes::new().app_manifest(manifest))
        .expect("Tauri application configuration must be valid");
    // Tauri owns the permission body. R5 additionally requires these two lines
    // on checked-in TOML sources; retain the generator body byte for byte.
    const HEADER: &str = "# SPDX-License-Identifier: GPL-2.0-or-later
# Copyright (C) 2026 Open Mobile Emulator contributors
";
    for entry in std::fs::read_dir("permissions/autogenerated")
        .expect("generated permission directory must exist")
    {
        let path = entry
            .expect("generated permission entry must be readable")
            .path();
        if path.extension().is_none_or(|extension| extension != "toml") {
            continue;
        }
        let source = std::fs::read_to_string(&path).expect("generated permission must exist");
        if !source.starts_with(HEADER) {
            std::fs::write(path, format!("{HEADER}{source}"))
                .expect("generated permission license header must be written");
        }
    }
}
